@pytest.mark.e2e
@pytest.mark.asyncio
async def test_alias_routes_require_auth(
    anonymous_client: httpx.AsyncClient,
) -> None:
    for method, path in (
        ("GET", "/api/roles/buyer/draft"),
        ("PUT", "/api/roles/buyer/draft"),
        ("POST", "/api/roles/buyer/draft/submit"),
        ("GET", "/api/roles/buyer/me"),
        ("GET", "/api/roles/producer/draft"),
    ):
        r = await anonymous_client.request(method, path, json={})
        assert r.status_code == 401


@pytest.mark.e2e
@pytest.mark.asyncio
async def test_alias_admin_actions_require_admin(
    buyer_client: dict,
) -> None:
    client: httpx.AsyncClient = buyer_client["client"]
    fake_id = "00000000-0000-0000-0000-000000000000"

    r_approve = await client.post(f"/api/roles/buyer/{fake_id}/ai-approve")
    assert r_approve.status_code == 403

    r_reject = await client.post(f"/api/roles/buyer/{fake_id}/ai-reject")
    assert r_reject.status_code == 403


